def send(text: str) -> None:
    r = subprocess.run(
        [
            "curl", "-s", "-X", "POST",
            f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage",
            "-d", f"chat_id={CHAT_ID}",
            "-d", "parse_mode=HTML",
            "--data-urlencode", f"text={SESSION_URL}\n\n{text}",
        ],
        capture_output=True, text=True, timeout=60,
    )
    out = r.stdout
    ok = '"ok":true' in out
    print("SENT" if ok else f"FAILED: {out[:200]}  stderr: {r.stderr[:200]}")


